module gpio (
    input wire clk,
    input wire reset,
    input wire write_enable,
    input wire [3:0] write_data,

    output reg  [3:0] gpio_out,
    output wire [3:0] read_data
);

    // ???? ???? ??? ???? ??????? ??? GPIO
    assign read_data = gpio_out;

    // ????? ???? ????? ??? ???? ?????? ??? write_enable ?????
    always @(posedge clk or posedge reset) begin
        if (reset)
            gpio_out <= 4'b0000;
        else if (write_enable)
            gpio_out <= write_data;
    end

endmodule
