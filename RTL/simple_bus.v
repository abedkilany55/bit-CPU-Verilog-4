module simple_bus (
    input wire [3:0] address,
    input wire mem_read,
    input wire mem_write,
    input wire [3:0] cpu_write_data,

    input wire [3:0] ram_read_data,
    input wire [3:0] gpio_read_data,

    output wire [3:0] cpu_read_data,
    output wire [3:0] ram_address,
    output wire [3:0] ram_write_data,
    output wire [3:0] gpio_write_data,

    output wire ram_read,
    output wire ram_write,
    output wire gpio_write_enable
);

    wire ram_select;
    wire gpio_select;

    // ???????? 0 ??? 3 ????? ?????? ????????
    assign ram_select = (address <= 4'd3);

    // ??????? 4 ???? ???GPIO
    assign gpio_select = (address == 4'd4);

    // ????? ??????? ????????? ??? ???????
    assign ram_address = address;
    assign ram_write_data = cpu_write_data;

    // ????? ????? ?? ????? ??????? ??? ??? ?????? ???????
    assign ram_read  = mem_read  && ram_select;
    assign ram_write = mem_write && ram_select;

    // ????? ??????? ?? GPIO ??? ??????? 4
    assign gpio_write_enable = mem_write && gpio_select;
    assign gpio_write_data = cpu_write_data;

    // ?????? ???????? ???? ???? ???CPU
    assign cpu_read_data =
        mem_read && ram_select  ? ram_read_data  :
        mem_read && gpio_select ? gpio_read_data :
        4'b0000;

endmodule
